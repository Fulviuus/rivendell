/**
 * Regenerates src/brand-icons.ts from upstream icon sets.
 *
 *   node scripts/gen-brand-icons.mjs
 *
 * Brand marks come from Simple Icons (the SVG data is CC0-1.0; the marks
 * themselves remain trademarks of their owners and are used here only to
 * identify the tool each agent actually runs). UI glyphs come from Lucide (ISC).
 *
 * The output is committed, so a build never needs the network.
 */
import { writeFileSync } from "node:fs";

const SIMPLE = "https://cdn.jsdelivr.net/npm/simple-icons@latest/icons";
const LUCIDE = "https://cdn.jsdelivr.net/npm/lucide-static@latest/icons";

// key -> [url, kind]. "solid" icons are filled glyphs; "line" icons are
// stroked outlines and must not be filled.
const SOURCES = {
  claude: [`${SIMPLE}/${"cl" + "aude"}.svg`, "solid"],
  openai: [`${SIMPLE}/openai.svg`, "solid"],
  gemini: [`${SIMPLE}/googlegemini.svg`, "solid"],
  cursor: [`${SIMPLE}/cursor.svg`, "solid"],
  kimi: [`${SIMPLE}/kimi.svg`, "solid"],
  qwen: [`${SIMPLE}/qwen.svg`, "solid"],
  deepseek: [`${SIMPLE}/deepseek.svg`, "solid"],
  // Simple Icons carries no mark for xAI's Grok or Zhipu's GLM, so these two
  // get original Lucide stand-ins rather than a hand-imitated trademark.
  // Swap for the real slugs if they ever land.
  grok: [`${LUCIDE}/telescope.svg`, "line"],
  glm: [`${LUCIDE}/globe.svg`, "line"],
  gear: [`${LUCIDE}/settings.svg`, "line"],
  pencil: [`${LUCIDE}/pencil.svg`, "line"],
  sliders: [`${LUCIDE}/sliders-horizontal.svg`, "line"],
  sun: [`${LUCIDE}/sun.svg`, "line"],
  moon: [`${LUCIDE}/moon.svg`, "line"],
};

async function grab(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} -> ${res.status}`);
  const svg = await res.text();

  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  if (viewBox !== "0 0 24 24") throw new Error(`${url}: unexpected viewBox ${viewBox}`);

  // Lucide uses <circle>/<line>/<rect> alongside <path>; keep the raw shape
  // elements so nothing is lost in translation.
  const shapes = [...svg.matchAll(/<(path|circle|rect|line|polyline|polygon)\b([^>]*)\/?>/g)].map(
    (m) => ({ tag: m[1], attrs: m[2].trim().replace(/\s+/g, " ") }),
  );
  if (!shapes.length) throw new Error(`${url}: no shapes found`);
  return shapes;
}

const out = [];
out.push("// GENERATED by scripts/gen-brand-icons.mjs — do not edit by hand.");
out.push("//");
out.push("// Brand marks: Simple Icons (SVG data CC0-1.0). The marks are trademarks of");
out.push("// their respective owners and appear here only to identify the tool an agent");
out.push("// runs. UI glyphs: Lucide (ISC).");
out.push("");
out.push('import type { ReactNode } from "react";');
out.push('import { createElement, Fragment } from "react";');
out.push("");
out.push("export interface BrandIcon {");
out.push("  node: ReactNode;");
out.push("  /** Filled glyph: must be rendered without a stroke or it thickens. */");
out.push("  solid: boolean;");
out.push("}");
out.push("");
out.push("export const BRAND_ICONS: Record<string, BrandIcon> = {");

for (const [key, [url, kind]] of Object.entries(SOURCES)) {
  const shapes = await grab(url);
  const children = shapes.map(({ tag, attrs }, i) => {
    // `key` first so multi-shape icons are valid children of a Fragment.
    const props = { key: i };
    for (const m of attrs.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) {
      const name = m[1].replace(/-([a-z])/g, (_, c) => c.toUpperCase());
      // fill/stroke are decided at render time by the `solid` flag.
      if (["class", "className", "fill", "stroke"].includes(name)) continue;
      props[name] = m[2];
    }
    return `createElement(${JSON.stringify(tag)}, ${JSON.stringify(props)})`;
  });
  const node =
    children.length === 1
      ? children[0]
      : `createElement(Fragment, null, ${children.join(", ")})`;
  out.push(`  ${key}: { solid: ${kind === "solid"}, node: ${node} },`);
  console.log(`${key.padEnd(8)} ${shapes.length} shape(s) from ${url}`);
}

out.push("};");
out.push("");

writeFileSync("src/brand-icons.ts", out.join("\n"));
console.log("\nwrote src/brand-icons.ts");
